#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""genbig.py - generate the parts of the multi-hunk test program and
library (tests/bighunk.c).

Usage: genbig.py OUTDIR

Writes OUTDIR/big0.c ... big<N-1>.c and OUTDIR/bigexp.h.  Part p holds
filler functions bf<p>_<k>, a table btab<p>, a bss array bbss<p>, a
pointer bneg<p> with a negative addend into the next part's table, a
table bfn<p> of two functions of the previous part, bchain<p>, which
runs its fillers, reaches the next part's data, calls through bfn<p>
and then bchain<p+1>, and bent<p>, a library vector body.  The parts
are sized so that each is one object well under 64 KB but together they
need several code hunks.  bigexp.h gives the results the test expects,
computed here with the same 32-bit arithmetic.
"""

import os
import random
import sys

NPARTS = 3
NFUNCS = 56
NSTMTS = 52
M = 0xFFFFFFFF

# Arguments the test passes (tests/bighunk.c).
VPROG = 0x12345678
VLIB = 0x0BADCAFE
VENT = 0x00C0FFEE


def stmts(p, k):
    r = random.Random(p * 1000 + k)
    out = []
    for _ in range(NSTMTS):
        t = r.randrange(4)
        if t == 0:
            out.append(('mul', r.randrange(3, 62, 2), r.randrange(1 << 31)))
        elif t == 1:
            out.append(('xsr', r.randrange(1, 16)))
        elif t == 2:
            out.append(('asl', r.randrange(1, 10)))
        else:
            out.append(('xor', r.randrange(1 << 31)))
    return out


def ctext(s):
    if s[0] == 'mul':
        return "\tv = v * %dL + 0x%08xL;" % (s[1], s[2])
    if s[0] == 'xsr':
        return "\tv ^= v >> %d;" % s[1]
    if s[0] == 'asl':
        return "\tv += v << %d;" % s[1]
    return "\tv ^= 0x%08xL;" % s[1]


def run(body, v):
    for s in body:
        if s[0] == 'mul':
            v = (v * s[1] + s[2]) & M
        elif s[0] == 'xsr':
            v ^= v >> s[1]
        elif s[0] == 'asl':
            v = (v + (v << s[1])) & M
        else:
            v ^= s[1]
    return v


def tabval(p, i):
    return random.Random(-1 - p * 8 - i).randrange(1 << 31)


class Model:
    def __init__(self):
        self.f = [[stmts(p, k) for k in range(NFUNCS)] for p in range(NPARTS)]
        self.bss = [[0] * 4 for _ in range(NPARTS)]

    def chain(self, p, v):
        q, r = (p + 1) % NPARTS, (p + NPARTS - 1) % NPARTS
        for k in range(NFUNCS):
            v = run(self.f[p][k], v)
        v = (v + tabval(q, p & 7)) & M
        v = (v + tabval(q, p & 3)) & M
        self.bss[q][p & 3] = v
        if p > 0:
            v ^= self.bss[p][(p - 1) & 3]
        v ^= run(self.f[r][0], v)
        v = (v + run(self.f[r][NFUNCS - 1], v)) & M
        if p + 1 < NPARTS:
            v = self.chain(p + 1, v)
        return v

    def ent(self, p, v):
        return run(self.f[p][0], v) ^ tabval((p + 1) % NPARTS, 7)


def part(m, p):
    q, r = (p + 1) % NPARTS, (p + NPARTS - 1) % NPARTS
    o = ["/* SPDX-License-Identifier: MIT */",
         "/* Generated by tests/split/genbig.py: part %d of %d. */" % (p, NPARTS),
         "typedef unsigned long UL;", ""]
    o.append("extern UL btab%d[], bbss%d[];" % (q, q))
    o.append("extern UL bf%d_0(), bf%d_%d();" % (r, r, NFUNCS - 1))
    if p + 1 < NPARTS:
        o.append("extern UL bchain%d();" % (p + 1))
    o.append("UL bf%d_0();" % p)
    o.append("UL btab%d[8] = {" % p)
    o.append(",\n".join("\t0x%08xL" % tabval(p, i) for i in range(8)))
    o.append("};")
    o.append("UL bbss%d[4];" % p)
    o.append("UL *bneg%d = &btab%d[-1];" % (p, q))
    o.append("UL (*bfn%d[2])() = { bf%d_0, bf%d_%d };" % (p, r, r, NFUNCS - 1))
    o.append("")
    for k in range(NFUNCS):
        o.append("UL\nbf%d_%d(v)\nUL v;\n{" % (p, k))
        o.extend(ctext(s) for s in m.f[p][k])
        o.append("\treturn (v);\n}\n")
    o.append("UL\nbchain%d(v)\nUL v;\n{" % p)
    o.extend("\tv = bf%d_%d(v);" % (p, k) for k in range(NFUNCS))
    o.append("\tv += btab%d[%d];" % (q, p & 7))
    o.append("\tv += bneg%d[%d];" % (p, 1 + (p & 3)))
    o.append("\tbbss%d[%d] = v;" % (q, p & 3))
    if p > 0:
        o.append("\tv ^= bbss%d[%d];" % (p, (p - 1) & 3))
    o.append("\tv ^= (*bfn%d[0])(v);" % p)
    o.append("\tv += (*bfn%d[1])(v);" % p)
    if p + 1 < NPARTS:
        o.append("\tv = bchain%d(v);" % (p + 1))
    o.append("\treturn (v);\n}\n")
    o.append("UL\nbent%d(base, v)\nchar *base;\nUL v;\n{" % p)
    o.append("\treturn (bf%d_0(v) ^ btab%d[7]);\n}" % (p, q))
    return "\n".join(o) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    m = Model()
    for p in range(NPARTS):
        with open(os.path.join(d, "big%d.c" % p), 'w') as f:
            f.write(part(m, p))
    h = ["/* Generated by tests/split/genbig.py. */",
         "#define BIGPARTS\t%d" % NPARTS,
         "#define BIGVPROG\t0x%08xL" % VPROG,
         "#define BIGVLIB\t\t0x%08xL" % VLIB,
         "#define BIGVENT\t\t0x%08xL" % VENT,
         "#define BIGPROG\t\t0x%08xL" % Model().chain(0, VPROG),
         "#define BIGLIB\t\t0x%08xL" % Model().chain(0, VLIB)]
    h.extend("#define BIGENT%d\t0x%08xL" % (p, m.ent(p, VENT))
             for p in range(NPARTS))
    with open(os.path.join(d, "bigexp.h"), 'w') as f:
        f.write("\n".join(h) + "\n")


if __name__ == '__main__':
    main()
