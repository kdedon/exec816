/* Characters of the last key not yet returned. */
static UBYTE kmbuf[3];
static UWORD kmnext, kmcount;

/* A key press's characters into kmbuf; returns how many. */
static int
kmap(code, qual)
register int code;
int qual;
{
	register int c, lo;
	int shift;

	if (code >= KMSIZE || (lo = kmlo[code]) == 0)
		return (0);
	if (lo >= KM_CURSOR) {
		kmbuf[0] = 0x1b;
		kmbuf[1] = '[';
		kmbuf[2] = "ABCD"[lo - KM_CURSOR];
		return (3);
	}
	shift = (qual & (IEQUALIFIER_LSHIFT | IEQUALIFIER_RSHIFT)) != 0;
	if (lo >= 'a' && lo <= 'z' && (qual & IEQUALIFIER_CAPSLOCK))
		shift = !shift;
	c = shift ? kmup[code] : lo;
	if (qual & IEQUALIFIER_CONTROL) {
		if (lo == ' ' || (lo >= 0x40 && lo <= 0x7e))
			c = lo & 0x1f;
		else if (kmup[code] >= 0x40 && kmup[code] <= 0x5f)
			c = kmup[code] & 0x1f;
	}
	kmbuf[0] = kmbuf[1] = c;
	return (code == RAWKEY_KP_00 ? 2 : 1);
}

/*
 * The console's keyboard: the next character, or -1.  Never waits.
 * Callable with VI off, from interrupt code and before the device or the
 * interrupts are set up.
 */
int
kbd_getc()
{
	register int c;
	int s;

	s = intoff();
	while (kmcount == 0 && (c = kbd_getraw()) != -1) {
		kmcount = kmap(c & 0xff, c >> 8);
		kmnext = 0;
	}
	c = -1;
	if (kmcount != 0) {
		c = kmbuf[kmnext++];
		kmcount--;
	}
	intrest(s);
	return (c);
}
