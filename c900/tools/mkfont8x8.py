"""mkfont8x8.py - generate the LC display's 8x8 font.

Usage: mkfont8x8.py font8x8_basic.h > devices/font8x8.c

Takes ASCII 0x20-0x7E from Daniel Hepper's font8x8_basic.h
(https://github.com/dhepper/font8x8, public domain), whose glyphs are 8
bytes each with bit 0 leftmost, and writes them with bit 7 leftmost.
"""

import re
import sys

NOTICE = """\
 * Glyphs: font8x8_basic.h by Daniel Hepper (github.com/dhepper/font8x8),
 * public domain; after Marcel Sondaar's font8x8.h, which credits the
 * IBM VGA fonts and is likewise public domain."""


def load(path):
    src = open(path, encoding='ascii').read()
    if 'License: Public Domain' not in src:
        sys.exit('%s: no public domain notice' % path)
    body = src.split('font8x8_basic[128][8] = {', 1)
    if len(body) != 2:
        sys.exit('%s: no font8x8_basic table' % path)
    rows = re.findall(r'\{([^{}]*)\}', body[1])
    glyphs = [[int(x, 16) for x in r.split(',')] for r in rows[:128]]
    if len(glyphs) != 128 or any(len(g) != 8 for g in glyphs):
        sys.exit('%s: need 128 glyphs of 8 bytes' % path)
    return glyphs


def flip(b):
    return int('{:08b}'.format(b)[::-1], 2)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    glyphs = load(sys.argv[1])
    codes = list(range(0x20, 0x7F))
    out = sys.stdout
    out.write('/* SPDX-License-Identifier: MIT */\n/*\n')
    out.write(' * Generated by tools/mkfont8x8.py; do not edit.  The LC display\'s\n')
    out.write(' * 8x8 font: 8 bytes per glyph, one per raster, bit 7 leftmost, for\n')
    out.write(' * ASCII 0x20-0x7E; glyph c starts at (c - 0x20) * 8.\n *\n')
    out.write(NOTICE + '\n */\n')
    out.write('#include <exec/types.h>\n\nUBYTE font8x8[95 * 8] = {\n')
    for i, c in enumerate(codes):
        name = chr(c)
        if name in '\\*/':
            name = 'U+%04X' % c
        out.write('\t%s%s\t/* %s */\n' % (
            ', '.join('0x%02x' % flip(b) for b in glyphs[c]),
            ',' if i + 1 < len(codes) else '', name))
    out.write('};\n')


main()
