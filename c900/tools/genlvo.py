#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0-only
"""genlvo.py - generate LVO call macros and jump tables from a C900 .fd file.

Usage: genlvo.py FD HEADER [VECTORS.s LABEL BASESIZE]
       genlvo.py FD HEADER --table TABLE.c ARRAY PREFIX

An Amiga .fd file lists a library's functions in vector order from ##bias
(usually 30, the first vector after Open, Close, Expunge and Reserved);
each takes 6 bytes, so the n-th function's LVO is -(bias + 6n).  The C900
dialect keeps that layout and replaces an implemented function's 68000
register list with its C argument types, then names its return type and,
when the C function is not "x" + the name, "@" and that function:

    AllocMem(byteSize,requirements)(ULONG,ULONG) APTR
    CreateIORequest(port,size)(struct MsgPort *,ULONG) struct IORequest * @xCreateIOReq

A line that keeps a register list, or has nothing after "()()", is not
implemented.  ##private functions get no macro.

HEADER gets LVO<name> for every public function and, for implemented public ones,
a macro that casts each argument to its width (MWC has no prototypes) and
calls through the base: base + LVO, with the base as a hidden first
argument.  exec.library (##base _SysBase) passes no base: SysBase is a
global and its functions are the kernel's own.  Its header also declares
the C functions and, under EXEC_KERNEL, maps each macro to a direct call.

VECTORS.s (exec.library only) is SysBase, pointing at LABEL, then the jump
table in the data segment, from the most negative vector up to LABEL,
followed by BASESIZE bytes for the base: "jp f" for an implemented
function, "call kunimpl_" otherwise, so the stub can tell which vector
was called; kalertv labels the Alert vector, which kbadlvo calls so that
a patched Alert sees the alert.  The table is padded at its
low end to a multiple of 4 bytes, as MakeLibrary rounds lib_NegSize.

TABLE.c (a library loaded from disk) defines ARRAY, the function pointer
array MakeLibrary takes: PREFIXopen, PREFIXclose, PREFIXexpunge and
PREFIXnull for the four standard vectors, then every fd function in
vector order, PREFIXunimpl for one not implemented, ending in -1.
"""

import os
import re
import sys

LINE = re.compile(r'^(\w+)\(([^)]*)\)\(([^)]*)\)\s*(.*)$')
REGS = re.compile(r'^([ad][0-7][/,]?)+$')
SIGNIF = 15


def parse(path):
    base, bias, public = None, None, True
    funcs = []
    for n, raw in enumerate(open(path), 1):
        ln = raw.strip()
        if not ln or ln.startswith('*'):
            continue
        where = '%s:%d' % (path, n)
        if ln.startswith('##'):
            words = ln[2:].split()
            if words[0] == 'base':
                base = words[1].lstrip('_')
            elif words[0] == 'bias':
                b = int(words[1])
                if bias is not None and b != bias:
                    sys.exit('%s: ##bias %d, but the next vector is %d'
                             % (where, b, bias))
                bias = b
            elif words[0] in ('public', 'private'):
                public = words[0] == 'public'
            elif words[0] == 'end':
                break
            else:
                sys.exit('%s: unknown directive %s' % (where, ln))
            continue
        m = LINE.match(ln)
        if not m or bias is None:
            sys.exit('%s: not an fd function line' % where)
        name, args, regs, rest = m.groups()
        args = [a.strip() for a in args.split(',') if a.strip()]
        impl, rtype, types = None, None, None
        if not REGS.match(regs.replace(' ', '')) and rest:
            types = [t.strip() for t in regs.split(',') if t.strip()]
            if len(types) != len(args):
                sys.exit('%s: %d arguments, %d types'
                         % (where, len(args), len(types)))
            if '@' in rest:
                rest, impl = [s.strip() for s in rest.split('@')]
            else:
                impl = 'x' + name
            rtype = rest.strip()
            if len(impl) > SIGNIF:
                sys.exit('%s: %s is longer than %d characters; name the C '
                         'function with @' % (where, impl, SIGNIF))
            for a in args:
                if any(re.search(r'\b%s\b' % a, t) for t in types):
                    sys.exit('%s: argument %s names a type' % (where, a))
        funcs.append(dict(name=name, args=args, types=types, rtype=rtype,
                          impl=impl, public=public, lvo=-bias))
        bias += 6
    if base is None:
        sys.exit('%s: no ##base' % path)
    return base, funcs


def ptr(rtype):
    return rtype if rtype.endswith('*') else rtype + ' '


def header(path, fdname, base, funcs, negsize):
    guard = 'LVO_' + re.sub(r'\W', '_', os.path.basename(path)).upper()
    kernel = base == 'SysBase'
    o = ['/* SPDX-License-Identifier: MIT */',
         '/* Generated by c900/tools/genlvo.py from %s; do not edit. */'
         % fdname, '#ifndef ' + guard, '#define ' + guard, '']
    for f in funcs:
        if f['public']:
            o.append('#define LVO%s (%d)' % (f['name'], f['lvo']))
    if negsize:
        o.append('#define %s_NEGSIZE %d' % (base.upper(), negsize))
    o.append('')
    calls = [f for f in funcs if f['impl'] and f['public']]
    if kernel:
        for f in calls:
            o.append('%s%s();' % (ptr(f['rtype']), f['impl']))
        o.append('')
    for f in calls:
        params = ', '.join(f['args'])
        cast = ', '.join('(%s)(%s)' % (t, a)
                         for t, a in zip(f['types'], f['args']))
        sig = '%s(%s)' % (f['name'], params)
        fn = '(*(%s(*)())((char *)%s + LVO%s))' % (
            ptr(f['rtype']), base, f['name'])
        lvo = '%s(%s)' % (fn, cast if kernel else
                          ', '.join([base] + ([cast] if cast else [])))
        if kernel:
            o.append('#ifdef EXEC_KERNEL')
            o.append('#define %s %s(%s)' % (sig, f['impl'], cast))
            o.append('#else')
        o.append('#define %s \\\n\t%s' % (sig, lvo))
        if kernel:
            o.append('#endif')
    o.append('')
    o.append('#endif')
    return '\n'.join(o) + '\n'


def vectors(fdname, funcs, label, size):
    neg = len(funcs) * 6
    pad = -neg % 4
    o = ['/ SPDX-License-Identifier: MIT',
         '/ Generated by c900/tools/genlvo.py from %s; do not edit.' % fdname,
         '/ lib_NegSize %d: %d vectors and %d bytes of padding.'
         % (neg + pad, len(funcs), pad), '',
         '\t.globl\tSysBase_, %s, kunimpl_, kbadlvo_, kalertv_' % label]
    for impl in sorted(set(f['impl'] for f in funcs if f['impl'])):
        o.append('\t.globl\t%s_' % impl)
    o += ['',
          '/ An unimplemented vector is "call kunimpl_": the vector\'s end is',
          '/ on the stack above the caller\'s return, as kbadlvo\'s argument.',
          '\t.shri', 'kunimpl_:', '\tcall\tkbadlvo_', '\tinc\tr15, $4',
          '\tret', '',
          '/ Linked directly after crt.o, which has no data: SysBase is the',
          '/ first long of the data segment (shared data precedes private).',
          '\t.shrd', 'SysBase_:', '\t.long\t%s' % label, '',
          '\t.prvd']
    if pad:
        o.append('\t.blkb\t%d' % pad)
    for f in reversed(funcs):
        if f['name'] == 'Alert':
            o.append('kalertv_:')
        if f['impl']:
            o.append('\tjp\t%s_\t\t/ %d %s' % (f['impl'], f['lvo'], f['name']))
        else:
            o.append('\tcall\tkunimpl_\t/ %d %s' % (f['lvo'], f['name']))
    o += ['%s:' % label, '\t.blkb\t%d' % size]
    return '\n'.join(o) + '\n', neg + pad


def table(fdname, funcs, array, prefix):
    std = [prefix + n for n in ('open', 'close', 'expunge', 'null')]
    names = std + [f['impl'] or prefix + 'unimpl' for f in funcs]
    o = ['/* SPDX-License-Identifier: MIT */',
         '/* Generated by c900/tools/genlvo.py from %s; do not edit. */'
         % fdname, '#include <exec/types.h>', '']
    for n in sorted(set(names)):
        o.append('extern long %s();' % n)
    o += ['', 'APTR %s[] = {' % array]
    o += ['\t(APTR)%s,' % n for n in names]
    o += ['\t(APTR)-1L', '};']
    return '\n'.join(o) + '\n'


def write(path, text):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    if not os.path.exists(path) or open(path).read() != text:
        with open(path, 'w') as f:
            f.write(text)


def main():
    if len(sys.argv) not in (3, 6, 7):
        sys.exit(__doc__)
    fd, hpath = sys.argv[1:3]
    fdname = 'fd/' + os.path.basename(fd)
    base, funcs = parse(fd)
    neg = 0
    if len(sys.argv) == 7:
        if sys.argv[3] != '--table':
            sys.exit(__doc__)
        write(sys.argv[4], table(fdname, funcs, sys.argv[5], sys.argv[6]))
    elif len(sys.argv) == 6:
        s, neg = vectors(fdname, funcs, sys.argv[4], int(sys.argv[5]))
        write(sys.argv[3], s)
    write(hpath, header(hpath, fdname, base, funcs, neg))


if __name__ == '__main__':
    main()
