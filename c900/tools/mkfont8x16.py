def load(path):
    data = open(path, 'rb').read()
    if data[:2] == b'\x1f\x8b':
        data = gzip.decompress(data)
    if data[:2] != b'\x36\x04':
        sys.exit('%s: not a PSF1 font' % path)
    mode, height = data[2], data[3]
    if height != 16 or not mode & 0x02:
        sys.exit('%s: need 8x16 glyphs with a Unicode table' % path)
    n = 512 if mode & 0x01 else 256
    glyphs = [data[4 + i * 16:4 + (i + 1) * 16] for i in range(n)]
    umap = {}
    p = 4 + n * 16
    for i in range(n):
        while True:
            (u,) = struct.unpack_from('<H', data, p)
            p += 2
            if u == 0xFFFF:
                break
            if u != 0xFFFE:
                umap.setdefault(u, i)
    return glyphs, umap


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    glyphs, umap = load(sys.argv[1])
    codes = list(range(0x20, 0x7F))
    if any(c not in umap for c in codes):
        sys.exit('%s: font lacks ASCII' % sys.argv[1])
    out = sys.stdout
    out.write('/* SPDX-License-Identifier: MIT */\n/*\n')
    out.write(' * Generated by tools/mkfont8x16.py; do not edit.  The shared 8x16\n')
    out.write(' * font: 16 bytes per glyph, one per raster, bit 7 leftmost, for\n')
    out.write(' * ASCII 0x20-0x7E; glyph c starts at (c - 0x20) * 16.\n *\n')
    out.write(NOTICE + '\n */\n')
    out.write('#include <exec/types.h>\n\nUBYTE font8x16[95 * 16] = {\n')
    rows = codes
    for i, c in enumerate(rows):
        g = glyphs[umap[c]]
        name = chr(c)
        if name in '\\*/':
            name = 'U+%04X' % c
        out.write('\t%s%s\t/* %s */\n' % (', '.join('0x%02x' % b for b in g),
                                            ',' if i + 1 < len(rows) else '', name))
    out.write('};\n')


main()
